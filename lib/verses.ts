/** Today's (this hour's) reference. */
export function verseRefForHour(hoursSinceEpoch: number): string {
  return VERSE_REFS[((hoursSinceEpoch % VERSE_REFS.length) + VERSE_REFS.length) % VERSE_REFS.length];
}

export function isVerseRef(ref: string): boolean {
  return VERSE_REFS.includes(ref);
}

/** The API's text as one paragraph: its line breaks are poetry layout, not sentences. */
export function tidyVerseText(text: string): string {
  return text.replace(/\s+/g, ' ').trim();
}

